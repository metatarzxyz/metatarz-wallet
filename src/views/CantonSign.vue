<template>
  <ion-page>
    <ion-header>
      <ion-toolbar>
        <ion-title>{{ kind === "tx" ? "Canton Transaction" : "Canton Sign Message" }}</ion-title>
      </ion-toolbar>
    </ion-header>

    <ion-content class="ion-padding">
      <ion-list v-if="req">
        <ion-item v-if="isWc">
          <ion-text style="font-size: 0.9rem">
            Request from:
            <b>{{ req.peer?.name || "Unknown dApp" }}</b>
            <div style="word-break: break-all">
              <b>{{ req.peer?.url || "No URL given" }}</b>
            </div>
            <div style="font-size: 0.8rem; opacity: 0.8">via WalletConnect</div>
          </ion-text>
        </ion-item>
        <ion-item v-if="isWc" :color="wcDanger ? 'danger' : undefined">
          <ion-text style="font-size: 0.9rem">
            WalletConnect Verify:
            <b v-if="req.peer?.verify?.isScam">known scam domain</b>
            <b v-else-if="req.peer?.verify?.validation === 'INVALID'"
              >domain mismatch, this may not be {{ req.peer?.url }}</b
            >
            <ion-text v-else-if="req.peer?.verify?.validation === 'VALID'" color="success"
              ><b>verified domain</b></ion-text
            >
            <ion-text v-else color="warning"><b>unverified</b></ion-text>
          </ion-text>
        </ion-item>
        <ion-item v-else>
          <ion-text style="font-size: 0.9rem">
            Request from:
            <b style="word-break: break-all">{{ req.origin || "Unknown site" }}</b>
          </ion-text>
        </ion-item>
        <ion-item v-if="req.subframe">
          <ion-text color="warning" style="font-size: 0.9rem">
            This request comes from an embedded frame, not from the page shown in the
            address bar. Only approve if you trust this site.
          </ion-text>
        </ion-item>
        <ion-item v-if="!isWc && (req.origin ?? '').startsWith('http:')">
          <ion-text color="warning" style="font-size: 0.9rem">
            This site does not use a secure (https) connection.
          </ion-text>
        </ion-item>
        <ion-item>
          <ion-text style="font-size: 0.9rem">
            Network: <b>{{ req.networkId }}</b>
          </ion-text>
        </ion-item>
        <ion-item>
          <ion-text style="font-size: 0.9rem">
            {{ kind === "tx" ? "Acting party" : "Signing party" }}
            <span v-if="req.accountName">({{ req.accountName }})</span>:
            <div style="word-break: break-all; font-size: 0.8rem">
              <b>{{ req.party }}</b>
            </div>
          </ion-text>
        </ion-item>

        <template v-if="kind === 'tx'">
          <ion-item>
            <ion-text color="warning" style="font-size: 0.9rem">
              <b
                >This transaction is constructed by the dApp. Only approve if you trust this
                site.</b
              >
            </ion-text>
          </ion-item>
          <ion-item>
            <ion-text style="font-size: 0.85rem; word-break: break-all">
              Command ID: <b>{{ req.commandId }}</b>
              <span v-if="req.commandIdGenerated"> (generated by the wallet)</span>
            </ion-text>
          </ion-item>
          <ion-item>
            <div style="width: 100%; font-size: 0.85rem">
              <div>
                <b>{{ req.commands?.length ?? 0 }}</b>
                command{{ (req.commands?.length ?? 0) === 1 ? "" : "s" }}:
              </div>
              <ol style="margin: 0.3rem 0; padding-left: 1.2rem">
                <li v-for="(c, i) of req.commands ?? []" :key="i" style="word-break: break-all">
                  <b>{{ c.type }}</b>
                  <div v-if="c.templateId">Template: {{ c.templateId }}</div>
                  <div v-if="c.choice">Choice: {{ c.choice }}</div>
                  <div v-if="c.contractId">Contract: {{ c.contractId }}</div>
                </li>
              </ol>
              <div>
                Disclosed contracts: <b>{{ req.disclosedCount ?? 0 }}</b>
              </div>
            </div>
          </ion-item>
          <ion-item>
            <div style="width: 100%">
              <div style="font-size: 0.85rem; margin: 0.3rem 0">Full request from the site:</div>
              <pre class="raw" v-text="req.rawJson"></pre>
            </div>
          </ion-item>
        </template>

        <template v-else>
          <ion-item v-if="hiddenChars">
            <ion-text color="warning" style="font-size: 0.9rem">
              This message contains invisible or control characters that may hide part of
              its text. Only sign it if you fully trust this site.
            </ion-text>
          </ion-item>
          <ion-item>
            <div style="width: 100%">
              <div style="font-size: 0.85rem; margin: 0.3rem 0">
                Message ({{ (req.message ?? "").length }} characters), signed exactly as shown:
              </div>
              <pre class="raw" v-text="req.message"></pre>
            </div>
          </ion-item>
        </template>

        <ion-item>Auto-reject Timer:&nbsp;<b>{{ timerReject }}</b></ion-item>
        <ion-item class="no-inner-border">
          <ion-button @click="onCancel">Reject</ion-button>
          <ion-button v-if="wcDanger && !confirmDanger" color="danger" @click="confirmDanger = true"
            >I understand the risk</ion-button
          >
          <ion-button v-else @click="onApprove">{{ kind === "tx" ? "Approve" : "Sign" }}</ion-button>
        </ion-item>
      </ion-list>
      <ion-list v-else>
        <ion-item>
          <ion-text>{{ loadError || "Loading request..." }}</ion-text>
        </ion-item>
        <ion-item class="no-inner-border">
          <ion-button @click="onCancel">Reject</ion-button>
        </ion-item>
      </ion-list>
      <ion-loading
        :is-open="loading"
        message="Please wait..."
        :key="`k${loading}`"
        @didDismiss="loading = false"
      />
    </ion-content>
  </ion-page>
</template>

<script lang="ts" setup>
import { ref, computed } from "vue";
import {
  IonContent,
  IonHeader,
  IonPage,
  IonTitle,
  IonToolbar,
  IonItem,
  IonButton,
  IonText,
  IonList,
  IonLoading,
  modalController,
  onIonViewWillEnter,
} from "@ionic/vue";
import { useRoute } from "vue-router";
import { approve, walletGetData, walletPing } from "@/extension/userRequest";
import {
  blockLockout,
  getAccounts,
  hexTostr,
  unBlockLockout,
} from "@/utils/platform";
import UnlockModal from "@/views/UnlockModal.vue";
import { setUnlockModalState } from "@/utils/unlockStore";
import type { WcPeer, WcVerify } from "@/extension/wcConstants";

// Request data comes from the service worker via wallet_get_data (keyed by this
// popup's window), never from the URL, so long requests are shown losslessly.
type CantonRequest = {
  kind: "tx" | "message";
  origin: string;
  subframe: boolean;
  networkId: string;
  party: string;
  accountName: string;
  address: string;
  // tx
  commandId?: string;
  commandIdGenerated?: boolean;
  commands?: { type: string; templateId?: string; choice?: string; contractId?: string }[];
  disclosedCount?: number;
  rawJson?: string;
  // message
  message?: string;
  // WalletConnect requests: origin is the dApp's metadata URL
  via?: "walletconnect";
  peer?: WcPeer & { verify: WcVerify };
};

const route = useRoute();
const rid = (route?.params?.rid as string) ?? "";
let routeKind = "message";
try {
  routeKind = JSON.parse(hexTostr((route?.params?.param as string) ?? ""))?.kind ?? "message";
} catch {
  // ignore
}

const req = ref(null as CantonRequest | null);
const kind = computed(() => req.value?.kind ?? routeKind);
const loadError = ref("");
const confirmDanger = ref(false);
const isWc = computed(() => req.value?.via === "walletconnect");
const wcDanger = computed(
  () => isWc.value && (req.value?.peer?.verify?.isScam === true || req.value?.peer?.verify?.validation === "INVALID")
);
const loading = ref(false);
const timerReject = ref(140);
let interval: any;

// Zero-width, bidi override and other control characters (newline and tab are fine)
// eslint-disable-next-line no-control-regex
const HIDDEN_CHARS = /[\u0000-\u0008\u000B\u000C\u000E-\u001F\u007F-\u009F​-‏‪-‮⁠-⁩﻿]/;
const hiddenChars = computed(() => HIDDEN_CHARS.test(req.value?.message ?? ""));

const loadRequest = async () => {
  // The service worker stores the data right after it opens this window: retry briefly
  for (let i = 0; i < 20; i++) {
    const data = (await walletGetData(rid)) as CantonRequest | undefined;
    if (data && (data.kind === "tx" || data.kind === "message")) {
      req.value = data;
      return;
    }
    await new Promise((r) => setTimeout(r, 150));
  }
  loadError.value = "The request could not be loaded.";
};

const onCancel = async () => {
  if (interval) {
    clearInterval(interval);
  }
  // Lift the auto-lock suspension before the window (and this script) goes away
  try {
    await unBlockLockout();
  } catch {
    // ignore
  }
  window.close();
};

const openModal = async () => {
  const modal = await modalController.create({
    component: UnlockModal,
    animated: true,
    focusTrap: false,
    backdropDismiss: false,
    componentProps: {
      unlockType: kind.value === "tx" ? "transaction" : "message",
    },
  });
  await modal.present();
  setUnlockModalState(true);
  const { role } = await modal.onWillDismiss();
  if (role === "confirm") return true;
  await setUnlockModalState(false);
  return false;
};

const onApprove = async () => {
  if (!req.value || (wcDanger.value && !confirmDanger.value)) return;
  loading.value = true;
  if (interval) {
    clearInterval(interval);
  }
  const address = req.value.address.toLowerCase();
  const signer = (await getAccounts()).find((a) => a.address.toLowerCase() === address);
  loading.value = false;
  if ((signer?.pk ?? "").length !== 66) {
    const modalResult = await openModal();
    if (!modalResult) {
      onCancel();
      return;
    }
  }
  await unBlockLockout(true);
  approve(rid);
};

onIonViewWillEnter(async () => {
  blockLockout();
  loadRequest();
  interval = setInterval(async () => {
    if (timerReject.value <= 0) {
      onCancel();
      return;
    }
    timerReject.value -= 1;
    walletPing();
  }, 1000) as any;
});
</script>

